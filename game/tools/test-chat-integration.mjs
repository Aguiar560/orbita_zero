import assert from 'node:assert/strict';
import { ambienteChat, aguardar } from './lib/chat-test-env.mjs';

const e = await ambienteChat();
let verificacoes = 0;
function ok(condicao, mensagem) { assert.ok(condicao, mensagem); verificacoes++; }
async function api(id, p, status = 200, extras) {
  const r = await e.api(id, p, extras);
  assert.equal(r.status, status, `${p.op}: ${JSON.stringify(r.data)}`); verificacoes++;
  return r.data;
}
try {
  const origem = await e.mf.dispatchFetch('https://chat.test/chat/socket', { headers: { origin: 'https://intruso.invalid', upgrade: 'websocket' } });
  ok(origem.status === 403, 'Origem estranha recusada antes do upgrade');
  await api('alfa', { op: 'ticket' }, 401, { exp: 1 });
  await api('alfa', { op: 'ticket' }, 401, { iss: 'https://outro.invalid/auth/v1' });
  const visitante = await api('anonimo', { op: 'ticket' }, 200, { email: '', is_anonymous: true });
  ok(!visitante.perfil.podeEnviar, 'Anônimo somente leitura');
  await api('anonimo', { op: 'enviar', conversa: 'global', texto: 'Não permitido', clienteId: 'anon' }, 403, { email: '', is_anonymous: true });
  await api('sem-apelido', { op: 'enviar', conversa: 'global', texto: 'Não permitido', clienteId: 'sem-nome' }, 403);
  for (const id of ['alfa', 'beta', 'gama', 'moderador']) await api(id, { op: 'estado' });
  const alfa = await e.socket('alfa'), beta = await e.socket('beta'), gama = await e.socket('gama');
  await aguardar(() => alfa.eventos.some(e => e.tipo === 'pronto') && beta.eventos.some(e => e.tipo === 'pronto') && gama.eventos.some(e => e.tipo === 'pronto'));
  const global = await api('alfa', { op: 'enviar', conversa: 'global', texto: 'Olá, pilotos! 🚀 <img src=x onerror=alert(1)>', clienteId: 'global-1' });
  await aguardar(() => beta.eventos.some(e => e.mensagem?.id === global.mensagem.id));
  ok(gama.eventos.some(e => e.mensagem?.id === global.mensagem.id), 'Global entregue ao terceiro jogador');
  ok((await api('anonimo', { op: 'historico', conversa: 'global' }, 200, { email: '', is_anonymous: true })).mensagens.length === 1, 'Anônimo lê global');
  const repetida = await api('alfa', { op: 'enviar', conversa: 'global', texto: global.mensagem.texto, clienteId: 'global-1' });
  ok(repetida.mensagem.id === global.mensagem.id, 'Reenvio idempotente');
  await api('alfa', { op: 'enviar', conversa: 'global', texto: 'Outro texto', clienteId: 'global-1' }, 409);
  const { conversa } = await api('alfa', { op: 'solicitar', alvo: 'beta' });
  await api('alfa', { op: 'enviar', conversa, texto: 'Ainda não aceitou', clienteId: 'pendente' }, 403);
  await api('gama', { op: 'historico', conversa }, 403);
  await api('gama', { op: 'responder', conversa, aceitar: true }, 403);
  await api('alfa', { op: 'responder', conversa, aceitar: true }, 403);
  await api('beta', { op: 'responder', conversa, aceitar: true });
  const privada = await api('alfa', { op: 'enviar', conversa, texto: 'Mensagem particular', clienteId: 'privada-1' });
  await aguardar(() => beta.eventos.some(e => e.mensagem?.id === privada.mensagem.id));
  ok(!gama.eventos.some(e => e.mensagem?.id === privada.mensagem.id), 'Terceiro socket nunca recebe privada');
  await api('gama', { op: 'enviar', conversa, texto: 'Injetar', clienteId: 'invasao' }, 403);
  ok((await api('beta', { op: 'estado' })).conversas[0].naoLidas === 1, 'Não lida persistida');
  await api('beta', { op: 'ler', conversa, cursor: 999999 });
  ok((await api('beta', { op: 'estado' })).conversas[0].naoLidas === 0, 'Cursor limitado ao histórico real');
  beta.ws.close();
  await api('gama', { op: 'enviar', conversa: 'global', texto: 'Teste de retenção', clienteId: 'retencao-global' });
  await api('beta', { op: 'enviar', conversa, texto: 'Disponível offline', clienteId: 'privada-2' });
  const reconectado = await e.socket('beta');
  await aguardar(() => reconectado.eventos.some(e => e.tipo === 'pronto'));
  ok((await api('beta', { op: 'historico', conversa })).mensagens.length === 2, 'Histórico recuperado após reconexão');
  await api('beta', { op: 'bloquear', alvo: 'alfa' });
  await api('alfa', { op: 'enviar', conversa, texto: 'Bloqueado', clienteId: 'bloqueado' }, 403);
  const aposBloqueio = await api('alfa', { op: 'enviar', conversa: 'global', texto: 'Global filtrado', clienteId: 'global-bloqueado' });
  ok(!reconectado.eventos.some(e => e.mensagem?.id === aposBloqueio.mensagem.id), 'Bloqueio respeitado em socket já aberto');
  ok(!(await api('beta', { op: 'historico', conversa: 'global' })).mensagens.some(m => m.autor === 'alfa'), 'Bloqueio filtra histórico');
  await api('beta', { op: 'denunciar', mensagem: privada.mensagem.id, motivo: 'Assédio em mensagem particular' });
  await api('gama', { op: 'denunciar', mensagem: privada.mensagem.id, motivo: 'Não pode acessar' }, 403);
  await api('gama', { op: 'denuncias' }, 403);
  const fila = await api('moderador', { op: 'denuncias' });
  ok(fila.denuncias.length === 1, 'Fila de moderação recebe evidência privada denunciada');
  const denuncia = fila.denuncias[0].id;
  await api('moderador', { op: 'moderar', denuncia, acao: 'remover', motivo: 'Conteúdo inadequado' });
  ok((await api('alfa', { op: 'historico', conversa })).mensagens.some(m => m.removida && !m.texto), 'Remoção preserva tombstone sem texto');
  await api('moderador', { op: 'moderar', denuncia, acao: 'silenciar', horas: 24, motivo: 'Assédio' });
  await api('alfa', { op: 'enviar', conversa: 'global', texto: 'Silenciado', clienteId: 'silenciado' }, 403);
  await api('moderador', { op: 'moderar', denuncia, acao: 'banir', horas: 24, motivo: 'Reincidência' });
  await api('alfa', { op: 'ticket' }, 403);
  await api('moderador', { op: 'moderar', denuncia, acao: 'revogar', motivo: 'Revisão administrativa' });
  await api('beta', { op: 'desbloquear', alvo: 'alfa' });
  await api('gama', { op: 'preferencias', privadas: false });
  await api('beta', { op: 'solicitar', alvo: 'gama' }, 403);
  const encontrado = await api('beta', { op: 'buscar', apelido: 'Piloto A' });
  ok(encontrado.jogadores.some(j => j.id === 'alfa'), 'Busca pelo apelido');
  for (let i = 0; i < 3; i++) await api('spam', { op: 'enviar', conversa: 'global', texto: 'Limite', clienteId: `spam-${i}` });
  await api('spam', { op: 'enviar', conversa: 'global', texto: 'Limite', clienteId: 'spam-4' }, 429);
  const replay = (await api('gama', { op: 'ticket' })).ticket;
  const primeiro = await e.socket('replay-1', replay);
  await aguardar(() => primeiro.eventos.some(e => e.tipo === 'pronto'));
  const segundo = await e.socket('replay-2', replay);
  let fechado = false; segundo.ws.addEventListener('close', () => { fechado = true; });
  await aguardar(() => fechado);
  ok(!segundo.eventos.some(e => e.tipo === 'pronto'), 'Ticket só pode ser usado uma vez');
  const auditoria = await e.db.prepare('SELECT COUNT(*) n FROM chat_auditoria').first();
  ok(auditoria.n >= 5, 'Consulta e ações de moderação auditadas');
  const bindings = await e.mf.getBindings();
  await e.db.prepare("UPDATE chat_mensagens SET criado=0 WHERE clienteId IN ('retencao-global','privada-2')").run();
  await bindings.CHAT.get(bindings.CHAT.idFromName('global-v1')).fetch('https://chat/limpar', { method: 'POST' });
  ok((await e.db.prepare('SELECT COUNT(*) n FROM chat_mensagens WHERE criado=0').first()).n === 0, 'Retenção remove mensagens vencidas');
  const leitores = [];
  for (let i = 0; i < 25; i++) {
    const id = `carga-${i}`;
    await e.contas.prepare('INSERT INTO apelidos VALUES(?,?)').bind(id, `Carga ${i}`).run();
    leitores.push(await e.socket(id));
  }
  await aguardar(() => leitores.every(l => l.eventos.some(e => e.tipo === 'pronto')));
  const inicio = Date.now();
  const ids = [];
  for (let i = 0; i < 25; i++) ids.push((await api(`carga-${i}`, { op: 'enviar', conversa: 'global', texto: `Transmissão ${i}`, clienteId: `carga-${i}` })).mensagem.id);
  await aguardar(() => leitores.every(l => ids.every(id => l.eventos.some(e => e.mensagem?.id === id))));
  ok(true, '25 conexões simultâneas receberam 25 mensagens cada, sem lacunas');
  console.log(`Carga local: 625 entregas confirmadas em ${Date.now() - inicio} ms (não é dimensionamento de produção).`);
  const curto = (await api('expira', { op: 'ticket' }, 200, { exp: Math.floor(Date.now() / 1000) + 3 })).ticket;
  const expirando = await e.socket('expira', curto);
  let expirou = false; expirando.ws.addEventListener('close', () => { expirou = true; });
  await aguardar(() => expirou, 7000);
  ok(expirou, 'Socket fecha quando o JWT expira, mesmo sem novas mensagens');
  console.log(`Chat: ${verificacoes} verificações de integração passaram (JWT, D1, WebSocket e Durable Object reais locais).`);
} finally { await e.dispose(); }
